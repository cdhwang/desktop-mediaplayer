# -- metadata --------------------------------------------------------------


def test_read_metadata_mp3_style_tags(tagged_wav) -> None:
    meta = read_metadata(tagged_wav)
    assert meta.title == "My Title"
    assert meta.artist == "My Artist"
    assert meta.album == "My Album"
    assert meta.duration_ms > 0
    assert meta.cover_art is not None


def test_read_metadata_flac(tagged_flac) -> None:
    meta = read_metadata(tagged_flac)
    assert meta.title == "Flac Title"
    assert meta.artist == "Flac Artist"
    assert meta.cover_art is not None


def test_read_metadata_no_tags(tmp_path) -> None:
    path = tmp_path / "bare.wav"
    _write_wav(path)
    meta = read_metadata(str(path))
    assert meta.title == ""
    assert meta.duration_ms > 0
    assert meta.cover_art is None


def test_sidecar_cover_named_front_case_insensitive(tmp_path) -> None:
    path = tmp_path / "bare.wav"
    _write_wav(path)
    (tmp_path / "FRONT.png").write_bytes(_PNG_1x1)
    meta = read_metadata(str(path))
    assert meta.cover_art == _PNG_1x1


def test_sidecar_cover_prefers_named_over_single(tmp_path) -> None:
    path = tmp_path / "bare.wav"
    _write_wav(path)
    other = b"other-image-bytes"
    (tmp_path / "random.jpg").write_bytes(other)
    (tmp_path / "Cover.png").write_bytes(_PNG_1x1)
    meta = read_metadata(str(path))
    assert meta.cover_art == _PNG_1x1


def test_sidecar_cover_single_image_fallback(tmp_path) -> None:
    path = tmp_path / "bare.wav"
    _write_wav(path)
    data = b"only-one-image"
    (tmp_path / "whatever.jpg").write_bytes(data)
    meta = read_metadata(str(path))
    assert meta.cover_art == data


def test_sidecar_cover_multiple_unnamed_images_no_pick(tmp_path) -> None:
    path = tmp_path / "bare.wav"
    _write_wav(path)
    (tmp_path / "one.jpg").write_bytes(b"a")
    (tmp_path / "two.png").write_bytes(b"b")
    meta = read_metadata(str(path))
    assert meta.cover_art is None


def test_embedded_cover_takes_precedence_over_sidecar(tmp_path) -> None:
    path = tmp_path / "song.wav"
    _write_wav(path)
    from mutagen.wave import WAVE
    from mutagen.id3 import APIC

    audio = WAVE(str(path))
    if audio.tags is None:
        audio.add_tags()
    audio.tags.add(APIC(encoding=3, mime="image/png", type=3, desc="", data=_PNG_1x1))
    audio.save()
    (tmp_path / "cover.png").write_bytes(b"sidecar-should-not-win")
    meta = read_metadata(str(path))
    assert meta.cover_art == _PNG_1x1


def test_read_metadata_bad_file(tmp_path) -> None:
    path = tmp_path / "broken.mp3"
    path.write_bytes(b"not really audio")
    meta = read_metadata(str(path))
    assert isinstance(meta, Metadata)
    assert meta.title == ""


# -- central display -------------------------------------------------------


def test_central_display_pages(qtbot) -> None:
    display = CentralDisplay()
    qtbot.addWidget(display)
    assert display.has_page(PAGE_ALBUM_ART)
    assert display.current_page == PAGE_ALBUM_ART


def test_central_display_add_and_switch(qtbot) -> None:
    from PyQt6.QtWidgets import QLabel

    display = CentralDisplay()
    qtbot.addWidget(display)
    display.add_page(PAGE_SPECTRUM, QLabel("spectrum"))
    display.show_page(PAGE_SPECTRUM)
    assert display.current_page == PAGE_SPECTRUM
    display.show_page(PAGE_ALBUM_ART)
    assert display.current_page == PAGE_ALBUM_ART


def test_album_art_shows_metadata(qtbot) -> None:
    display = CentralDisplay()
    qtbot.addWidget(display)
    meta = Metadata(title="T", artist="A", cover_art=_PNG_1x1)
    display.show_metadata(meta, fallback_title="fallback")
    assert display.album_art.has_art
