def _write_wav(path: Path, seconds: float = 0.5, rate: int = 8000) -> None:
    n = int(rate * seconds)
    with wave.open(str(path), "w") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(rate)
        frames = bytearray()
        for i in range(n):
            frames += struct.pack("<h", int(20000 * math.sin(2 * math.pi * 440 * i / rate)))
        w.writeframes(bytes(frames))


# a tiny valid PNG generated by Qt (guaranteed decodable)
def _make_png() -> bytes:
    from PyQt6.QtCore import QBuffer, QByteArray
    from PyQt6.QtGui import QImage, QColor

    img = QImage(4, 4, QImage.Format.Format_RGB32)
    img.fill(QColor(120, 60, 200))
    ba = QByteArray()
    buf = QBuffer(ba)
    buf.open(QBuffer.OpenModeFlag.WriteOnly)
    img.save(buf, "PNG")
    return bytes(ba.data())


_PNG_1x1 = _make_png()


